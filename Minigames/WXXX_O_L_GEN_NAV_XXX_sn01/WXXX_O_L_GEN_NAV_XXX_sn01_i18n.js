  function normalizeLang(l) {
    const s = String(l || 'hu').toLowerCase().slice(0, 2);
    return SUPPORTED.includes(s) ? s : 'hu';
  }

  function getLang() {
    try {
      if (window.currentLanguage) return normalizeLang(window.currentLanguage);
      const p = new URLSearchParams(window.location.search).get('lang');
      if (p) return normalizeLang(p);
      const ls = localStorage.getItem('ebook_pirates_language') || localStorage.getItem('siteLang');
      if (ls) return normalizeLang(ls);
    } catch (e) {}
    return 'hu';
  }

  function setLang(l) {
    const lang = normalizeLang(l);
    window.currentLanguage = lang;
    try {
      localStorage.setItem('ebook_pirates_language', lang);
      localStorage.setItem('siteLang', lang);
    } catch (e) {}
    return lang;
  }

  function t(key, vars) {
    const lang = getLang();
    const pack = DICT[lang] || DICT.hu;
    let val = pack[key] !== undefined ? pack[key] : DICT.hu[key];
    if (typeof val === 'string' && vars) {
      Object.keys(vars).forEach(k => {
        val = val.replace(new RegExp(`\\{${k}\\}`, 'g'), vars[k]);
      });
    }
    return val;
  }

  function dict() {
    return DICT[getLang()] || DICT.hu;
  }

  return { SUPPORTED, DICT, getLang, setLang, dict, t };
